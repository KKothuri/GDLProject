"""Write results/SUMMARY.md: success per suite for every method, hard-task r sweep, same-GPU latency.
Reads the raw result dirs under results/ (not in git; they live on the cluster). Run from the project root."""
import glob, json, re
import numpy as np

SUITES = ["libero_spatial", "libero_object", "libero_goal", "libero_10"]
HARD = ["libero_object_task0", "libero_object_task1", "libero_goal_task9", "libero_10_task0", "libero_10_task9"]


def txt_success(pattern):
    """(successes, episodes) from OpenVLA/KERV text logs; newest log per task dir only."""
    k = n = 0
    groups = {}
    for f in glob.glob(pattern):
        groups.setdefault(f.rsplit("/", 1)[0] + ("" if "/logs/libero" in f else f.split("task")[-1][:2]), []).append(f)
    for fs in groups.values():
        L = open(max(fs)).read()
        k += len(re.findall(r"^Success: True", L, re.M)); n += len(re.findall(r"^Success:", L, re.M))
    return k, n


def json_success(pattern):
    k = n = 0
    for f in glob.glob(pattern):
        try:
            E = json.load(open(f))["episodes"]
        except Exception:
            continue
        k += sum(e["success"] for e in E); n += len(E)
    return k, n


def cell(kn):
    k, n = kn
    return f"{100 * k / n:.1f} ({n})" if n else "-"


out = ["# Results summary", "", "Generated by `scripts/summarize_results.py`. Success % (episodes). 50 trials/task, A40 GPUs.", "",
       "## Success rate per suite", "", "| Method | " + " | ".join(SUITES) + " |", "|---" * (len(SUITES) + 1) + "|"]
rows = {
    "OpenVLA (paper)": ["84.7", "88.4", "79.2", "53.7"],
    "OpenVLA (ours)": [cell(txt_success(f"results/baseline_openvla/{s}/logs/*.txt")) for s in SUITES],
    "Spec-VLA exact": [cell(json_success(f"results/specvla/spec/{s}_task*.json")) for s in SUITES],
    "Spec-VLA r=9": [cell(json_success(f"results/specvla/relaxed_r9/{s}_task*.json")) for s in SUITES],
    "Spec-VLA r=5": ["-", "-", "-", cell(json_success("results/specvla/relaxed_r5/libero_10_task*.json"))],
    "KERV as released": [cell(txt_success(f"results/kerv/{s}/logs/*/*.txt")) for s in SUITES],
    "KERV, forced Kalman off": [cell(txt_success(f"results/kerv_noKF/{s}/logs/*/*.txt")) for s in SUITES],
}
for k, v in rows.items():
    out.append(f"| {k} | " + " | ".join(v) + " |")
out += ["", "Spec-VLA r=5 was run only on libero_10 (paper's Long setting) and the hard tasks.", "",
        "## Hard tasks (largest exact vs r=9 gap; exact is flattered by this selection)", "",
        "| Method | " + " | ".join(HARD) + " | total |", "|---" * (len(HARD) + 2) + "|"]


def hard(m):
    cells, K, N = [], 0, 0
    for t in HARD:
        if m == "ar":
            s, tid = t.rsplit("_task", 1)
            k, n = txt_success(f"results/baseline_openvla/{s}/logs/*task{tid}-*.txt")
        else:
            k, n = json_success(f"results/specvla/{m}/{t}.json")
        cells.append(f"{k}/{n}" if n else "-"); K += k; N += n
    return cells + [f"{K}/{N}"]


for lab, m in [("OpenVLA", "ar"), ("exact", "spec"), ("r=3", "relaxed_r3"), ("r=5", "relaxed_r5"), ("r=9", "relaxed_r9")]:
    out.append(f"| {lab} | " + " | ".join(hard(m)) + " |")

out += ["", "## Same-GPU latency (one A40, task 0 per suite, 3 episodes). `ar` = SpecVLA AR mode (slow, see note)", "", "```"]
import subprocess, os
for stat in ["mean", "median"]:
    out.append(f"[{stat}]")
    out.append(subprocess.run(["python", "scripts/latency_summary.py"], capture_output=True, text=True,
                              env={**os.environ, "STAT": stat}).stdout.rstrip())
out += ["```", "", "Fair AR reference: stock OpenVLA HF generate = 7 LLM calls, ~283 ms/step on the same A40 "
        "(results/ar_timing). SpecVLA's AR mode makes 8 calls (~315 ms), so speedups above are vs a slow baseline.", ""]
open("results/SUMMARY.md", "w").write("\n".join(out))
print("\n".join(out))
